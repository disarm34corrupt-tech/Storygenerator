const META = {
  Theme:{color:"violet",icon:"✦",hint:"The central message"},
  Title:{color:"pink",icon:"✎",hint:"The name of your story"},
  Characters:{color:"teal",icon:"♟",hint:"Who brings the story to life?"},
  Setting:{color:"amber",icon:"⌖",hint:"Where and when it happens"},
  Conflict:{color:"coral",icon:"⚡",hint:"The main problem"},
  Climax:{color:"purple",icon:"↗",hint:"The turning point"},
  Resolution:{color:"green",icon:"✧",hint:"How the story ends"}
};
const categories=Object.keys(META), drawn={};
let busy=false, revealResolver=null;
const $=s=>document.querySelector(s);
const safe=t=>String(t).replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
function contentHTML(category,content){return Array.isArray(content)?`<ul>${content.map(x=>`<li>${safe(x)}</li>`).join("")}</ul>`:`<p>${safe(content)}</p>`;}
function renderCards(){
  $("#cardGrid").innerHTML=categories.map(category=>{
    const m=META[category],card=drawn[category];
    return `<article class="draw-card ${m.color}" data-category="${category}">
      <div class="card-topline"><span class="card-icon">${m.icon}</span><span class="card-count">${card?"CARD UNLOCKED":"15 CARDS IN DECK"}</span></div>
      <div class="card-category">${category.toUpperCase()}</div><p class="card-hint">${m.hint}</p>
      <div class="card-reveal ${card?"revealed":""}">${card?`<span class="card-id">${safe(card[0])}</span>${contentHTML(category,card[1])}`:`<div class="card-back"><span class="question-mark">?</span>YOUR STORY AWAITS</div>`}</div>
      <button class="draw-one" data-draw="${category}" ${busy?"disabled":""}>${card?"Draw Again ↻":`Draw ${category} →`}</button></article>`;
  }).join("");
  document.querySelectorAll("[data-draw]").forEach(b=>b.onclick=()=>drawOne(b.dataset.draw));
  updateProgress();
}
function updateProgress(){
  const n=categories.filter(c=>drawn[c]).length;
  $("#progressLabel").textContent=`${n}/7 Cards Drawn`;
  $("#progressFill").style.width=`${n/7*100}%`;
  $("#drawAll").disabled=busy||n===7;
  $("#copyCards").disabled=n===0;
  $("#startWriting").disabled=n!==7;
  $("#packEmpty").hidden=n>0;
  renderPack();
}
function renderPack(){
  $("#storyPack").innerHTML=categories.filter(c=>drawn[c]).map(c=>{
    const m=META[c],[id,content]=drawn[c];
    return `<article class="pack-item ${m.color}"><div class="pack-item-head"><span>${m.icon} ${c.toUpperCase()}</span><code>${safe(id)}</code></div>${contentHTML(c,content)}</article>`;
  }).join("");
}
function randomCard(c){const deck=CARD_DATA[c];return deck[Math.floor(Math.random()*deck.length)];}
function makeSparks(){
  $("#sparkleBurst").innerHTML=Array.from({length:28},(_,i)=>`<span class="spark" style="--angle:${i*360/28}deg;--distance:${65+Math.random()*100}px;animation-delay:${Math.random()*180}ms">✦</span>`).join("");
}
function revealGacha(category,card){
  const m=META[category];
  $("#prizeCard").className=`prize-card ${m.color}`;
  $("#prizeIcon").textContent=m.icon;
  $("#prizeCategory").textContent=category.toUpperCase();
  $("#prizeId").textContent=card[0];
  $("#prizeContent").innerHTML=contentHTML(category,card[1]);
  makeSparks();$("#gachaOverlay").hidden=false;
}
function closeGacha(){ $("#gachaOverlay").hidden=true;if(revealResolver){const done=revealResolver;revealResolver=null;done();} }
function waitForContinue(){
  return new Promise(resolve=>{revealResolver=resolve;$("#gachaContinue").onclick=closeGacha;});
}
function sleep(ms){return new Promise(resolve=>setTimeout(resolve,ms));}
async function drawOne(category){
  if(busy)return;busy=true;renderCards();
  document.querySelector(`[data-category="${category}"]`)?.classList.add("is-spinning");
  await sleep(650);drawn[category]=randomCard(category);busy=false;renderCards();revealGacha(category,drawn[category]);
}
async function drawAll(){
  if(busy)return;busy=true;
  for(const category of categories){
    renderCards();
    document.querySelector(`[data-category="${category}"]`)?.classList.add("is-spinning");
    await sleep(380);drawn[category]=randomCard(category);renderCards();revealGacha(category,drawn[category]);
    await waitForContinue();await sleep(120);
  }
  busy=false;renderCards();$("#storyPack").scrollIntoView({behavior:"smooth",block:"start"});
}
function resetAll(){
  if(busy)return;
  categories.forEach(c=>delete drawn[c]);$("#writingArea").hidden=true;$("#storyDraft").value="";
  $("#copyFeedback").textContent="";$("#draftFeedback").textContent="";
  document.querySelectorAll(".checklist input").forEach(x=>x.checked=false);
  updateChecklist();updateWordCount();renderCards();
}
function packText(){
  return categories.filter(c=>drawn[c]).map(c=>{
    const [id,content]=drawn[c],body=Array.isArray(content)?content.map(x=>"- "+x).join("\n"):content;
    return `${c.toUpperCase()} (${id})\n${body}`;
  }).join("\n\n");
}
async function copyText(text,feedback){
  try{await navigator.clipboard.writeText(text);feedback.textContent="Copied successfully! ✨";}
  catch{feedback.textContent="Clipboard unavailable. Please copy manually.";}
  setTimeout(()=>feedback.textContent="",2500);
}
function startWriting(){
  if(categories.some(c=>!drawn[c]))return;
  $("#writingArea").hidden=false;
  $("#writingPrompt").textContent=`Use "${drawn.Title[1]}" as your title. Connect all seven cards into a coherent narrative. Aim for 400–600 words.`;
  $("#writingArea").scrollIntoView({behavior:"smooth"});
}
function updateWordCount(){
  const text=$("#storyDraft").value.trim(),n=text?text.split(/\s+/).length:0;
  $("#wordCount").textContent=`${n} words`;
  $("#wordCount").style.color=n>=400&&n<=600?"#238455":"";
}
function updateChecklist(){
  const inputs=[...document.querySelectorAll(".checklist input")],n=inputs.filter(x=>x.checked).length;
  $("#checkProgress").textContent=`${n}/4 checks complete`;
}
$("#drawAll").onclick=drawAll;
$("#reset").onclick=resetAll;
$("#copyCards").onclick=()=>copyText(packText(),$("#copyFeedback"));
$("#startWriting").onclick=startWriting;
$("#storyDraft").addEventListener("input",updateWordCount);
$("#copyDraft").onclick=()=>copyText($("#storyDraft").value,$("#draftFeedback"));
document.querySelectorAll(".checklist input").forEach(x=>x.addEventListener("change",updateChecklist));
$("#gachaOverlay").addEventListener("click",e=>{if(e.target.classList.contains("gacha-backdrop"))closeGacha();});
document.addEventListener("keydown",e=>{if(e.key==="Escape"&&!$("#gachaOverlay").hidden)closeGacha();});
